"""
decision_framework.py — Ambiguity detection and decision point management for Agenton.

Provides:
  - DecisionOption  — one choice in a decision point (with pros/cons)
  - DecisionPoint   — a question presented to the user before execution
  - AmbiguityResult — what the LLM returns from extended _UNDERSTAND_INTENT_SYSTEM prompt
  - DecisionResolver — tracks open decisions and collects user responses
  - AMBIGUITY_SCHEMA — JSON Schema for LLM response validation

The decision framework integrates with the MasterAgent Conversational Agentic Loop:
  1. _understand_intent() returns AmbiguityResult with detected ambiguities
  2. Each DecisionPoint is streamed as a "decision_point" section in the generative card
  3. User clicks an option → frontend POSTs to /ui/decision
  4. DecisionResolver.receive_decision() unblocks the waiting coroutine
  5. MasterAgent continues execution with the user's choices in ctx.resolved_decisions

Usage:
    result = AmbiguityResult.from_llm_response(llm_json)
    resolver = DecisionResolver()

    for dp in result.decision_points:
        # Stream to frontend...
        await ctx.emit_section({"type": "decision_point", "content": dp.to_section_content()})

    # Wait for all resolutions (event-driven via asyncio.Event)
    decisions = await resolver.await_all(result.decision_points, timeout=300.0)
"""
from __future__ import annotations

import asyncio
import logging
from dataclasses import dataclass, field
from typing import Any

logger = logging.getLogger("agenton.decision_framework")


# ── Core types ─────────────────────────────────────────────────────────────────

@dataclass
class DecisionOption:
    """One option in a decision point presented to the user."""
    id: str                         # unique within this DecisionPoint; sent back in /ui/decision
    label: str                      # short display label, e.g. "All major brands"
    description: str = ""           # optional longer description
    pros: list[str] = field(default_factory=list)
    cons: list[str] = field(default_factory=list)
    is_default: bool = False        # pre-selected option in the UI

    def to_dict(self) -> dict:
        return {
            "id": self.id,
            "label": self.label,
            "description": self.description,
            "pros": self.pros,
            "cons": self.cons,
            "is_default": self.is_default,
        }


@dataclass
class DecisionPoint:
    """
    A question that must be resolved before the agent can proceed.

    Generated by the LLM via the extended _UNDERSTAND_INTENT_SYSTEM prompt,
    or synthetically when the cost engine detects near-equal strategies.
    """
    id: str                               # unique ID for this card session, e.g. "dp-1"
    question: str                         # the question text shown to the user
    options: list[DecisionOption]
    category: str = "clarification"       # "clarification" | "strategy" | "confirmation"
    context: str = ""                     # optional extra context below the question
    required: bool = True                 # if False, agent can proceed with default

    def default_option(self) -> DecisionOption | None:
        for opt in self.options:
            if opt.is_default:
                return opt
        return self.options[0] if self.options else None

    def find_option(self, option_id: str) -> DecisionOption | None:
        return next((o for o in self.options if o.id == option_id), None)

    def to_section_content(self) -> dict:
        """Serialize to the dict format expected by DecisionPointSectionView."""
        return {
            "id": self.id,
            "question": self.question,
            "options": [o.to_dict() for o in self.options],
            "category": self.category,
            "context": self.context,
            "required": self.required,
            "default_option_id": (self.default_option() or DecisionOption("", "")).id,
        }

    @classmethod
    def from_dict(cls, data: dict) -> "DecisionPoint":
        options = [
            DecisionOption(
                id=o.get("id", ""),
                label=o.get("label", ""),
                description=o.get("description", ""),
                pros=o.get("pros", []),
                cons=o.get("cons", []),
                is_default=o.get("id") == data.get("default"),
            )
            for o in data.get("options", [])
        ]
        return cls(
            id=data.get("id", f"dp-{id(data)}"),
            question=data.get("question", ""),
            options=options,
            category=data.get("category", "clarification"),
            context=data.get("context", ""),
            required=data.get("required", True),
        )


# ── LLM response parsing ───────────────────────────────────────────────────────

@dataclass
class AmbiguityResult:
    """Parsed output from the extended _UNDERSTAND_INTENT_SYSTEM prompt."""
    intent: str
    is_ambiguous: bool
    decision_points: list[DecisionPoint] = field(default_factory=list)
    confidence: float = 1.0
    raw: dict = field(default_factory=dict)

    @classmethod
    def from_llm_response(cls, data: dict) -> "AmbiguityResult":
        """
        Parse the LLM JSON response that includes ambiguity information.

        Expected JSON shape (additional fields alongside normal intent parsing):
        {
          "intent": "...",
          "is_ambiguous": true,
          "confidence": 0.8,
          "ambiguities": [
            {
              "id": "dp-1",
              "question": "Which laptop brands should I compare?",
              "category": "clarification",
              "context": "This affects how comprehensive the search will be.",
              "options": [
                {
                  "id": "all",
                  "label": "All major brands",
                  "pros": ["Comprehensive"],
                  "cons": ["Slower, more tokens"]
                },
                {
                  "id": "top3",
                  "label": "Top 3 by market share",
                  "pros": ["Fast, focused"],
                  "cons": ["May miss niche options"],
                  "is_default": true
                }
              ],
              "required": true
            }
          ]
        }
        """
        ambiguities_raw = data.get("ambiguities", [])
        decision_points: list[DecisionPoint] = []

        for i, amb in enumerate(ambiguities_raw):
            if "id" not in amb:
                amb["id"] = f"dp-{i + 1}"
            try:
                dp = DecisionPoint.from_dict(amb)
                if dp.options:  # skip malformed points with no options
                    decision_points.append(dp)
            except Exception as exc:
                logger.warning("Failed to parse ambiguity item %d: %s", i, exc)

        return cls(
            intent=data.get("intent", ""),
            is_ambiguous=bool(data.get("is_ambiguous", False)) or bool(decision_points),
            decision_points=decision_points,
            confidence=float(data.get("confidence", 1.0)),
            raw=data,
        )

    def has_required_decisions(self) -> bool:
        return any(dp.required for dp in self.decision_points)


