AMBIGUITY_SCHEMA: dict = {
    "type": "object",
    "properties": {
        "intent": {"type": "string"},
        "is_ambiguous": {"type": "boolean"},
        "confidence": {"type": "number", "minimum": 0, "maximum": 1},
        "ambiguities": {
            "type": "array",
            "items": {
                "type": "object",
                "required": ["question", "options"],
                "properties": {
                    "id": {"type": "string"},
                    "question": {"type": "string"},
                    "category": {
                        "type": "string",
                        "enum": ["clarification", "strategy", "confirmation"]
                    },
                    "context": {"type": "string"},
                    "required": {"type": "boolean"},
                    "default": {"type": "string", "description": "id of default option"},
                    "options": {
                        "type": "array",
                        "minItems": 2,
                        "items": {
                            "type": "object",
                            "required": ["id", "label"],
                            "properties": {
                                "id": {"type": "string"},
                                "label": {"type": "string"},
                                "description": {"type": "string"},
                                "pros": {"type": "array", "items": {"type": "string"}},
                                "cons": {"type": "array", "items": {"type": "string"}},
                            }
                        }
                    }
                }
            }
        }
    },
    "required": ["intent", "is_ambiguous"]
}


# ── System prompt extension ────────────────────────────────────────────────────

AMBIGUITY_PROMPT_EXTENSION = """
Additionally, if the user's request is ambiguous or has important decision points that
would significantly change the execution strategy, populate the "ambiguities" array.

For each ambiguity:
- Set "required": true only for decisions that MUST be resolved before proceeding
  (e.g., fundamentally different approaches). Use false for optional preferences.
- Provide 2-4 options per decision point with honest pros/cons for each.
- Mark one option as the sensible default.
- Set "category" to:
  - "clarification": missing information needed to understand the request
  - "strategy": different approaches to fulfilling the request
  - "confirmation": the action has significant effects (e.g., purchase, delete)

DO NOT create ambiguity points for trivial choices. Only surface decisions that
genuinely change the outcome in ways the user would care about.

Return the full response as a single JSON object matching the schema provided.
"""


# ── DecisionResolver ──────────────────────────────────────────────────────────

class DecisionResolver:
    """
    Tracks pending decision points and resolves them as user responses arrive.

    Usage:
        resolver = DecisionResolver()

        # Register all decision points before waiting
        resolver.register_all(decision_points)

        # In the AFP message handler when a user_decision arrives:
        resolver.receive_decision(decision_point_id, selected_option_id)

        # In the agent loop — blocks until all are resolved or timeout
        resolutions = await resolver.await_all(timeout=300.0)
    """

    def __init__(self) -> None:
        self._pending: dict[str, asyncio.Event] = {}
        self._resolutions: dict[str, str] = {}  # decision_point_id → option_id

    def register_all(self, decision_points: list[DecisionPoint]) -> None:
        """Register all required decision points for tracking."""
        for dp in decision_points:
            if dp.required and dp.id not in self._pending:
                self._pending[dp.id] = asyncio.Event()

    def receive_decision(self, decision_point_id: str, selected_option_id: str) -> bool:
        """
        Called when a user_decision AFP message arrives for this card.
        Returns True if the decision_point_id was registered and pending.
        """
        if decision_point_id not in self._pending:
            logger.warning("Received decision for unknown dp_id: %r", decision_point_id)
            return False
        self._resolutions[decision_point_id] = selected_option_id
        self._pending[decision_point_id].set()
        logger.debug("Decision resolved: %r → %r", decision_point_id, selected_option_id)
        return True

    def get_resolution(self, decision_point_id: str) -> str | None:
        """Get the resolved option_id for a decision point (or None if not yet resolved)."""
        return self._resolutions.get(decision_point_id)

    async def await_all(
        self,
        decision_points: list[DecisionPoint],
        timeout: float = 300.0,
    ) -> dict[str, str]:
        """
        Wait for all required decision points to be resolved.

        Returns dict of {decision_point_id: selected_option_id}.
        For timed-out or non-required decisions, uses the default option.
        """
        self.register_all(decision_points)

        required_ids = [dp.id for dp in decision_points if dp.required]

        try:
            await asyncio.wait_for(
                asyncio.gather(*[self._pending[dp_id].wait() for dp_id in required_ids]),
                timeout=timeout,
            )
        except asyncio.TimeoutError:
            logger.warning(
                "Decision timeout after %.0fs — using defaults for unresolved points",
                timeout,
            )
            # Fill in defaults for timed-out decisions
            for dp in decision_points:
                if dp.required and dp.id not in self._resolutions:
                    default = dp.default_option()
                    if default:
                        self._resolutions[dp.id] = default.id
                        logger.info(
                            "Using default option %r for dp %r", default.id, dp.id
                        )

        # Also populate non-required decisions with defaults if not resolved
        for dp in decision_points:
            if not dp.required and dp.id not in self._resolutions:
                default = dp.default_option()
                if default:
                    self._resolutions[dp.id] = default.id

        return dict(self._resolutions)

    def all_resolved(self) -> bool:
        return all(ev.is_set() for ev in self._pending.values())

    def pending_count(self) -> int:
        return sum(1 for ev in self._pending.values() if not ev.is_set())


HIGH_RISK_CAPABILITY_NAMES = {
    "ecommerce",
    "stripe",
    "google_api",
    "web_browse",
    "python_sandbox",
    "file_ops",
}

HIGH_RISK_KEYWORDS = (
    "delete",
    "remove",
    "refund",
    "charge",
    "checkout",
    "purchase",
    "buy",
    "cart",
    "submit",
    "send",
    "transfer",
    "move",
    "rm",
    "sudo",
    "pip install",
)


@dataclass
class TrustFilterVerdict:
    """Deterministic risk verdict before high-impact execution."""
    requires_confirmation: bool
    risk_level: str
    rationale: str
    matched_signals: list[str] = field(default_factory=list)

    def to_section_content(self) -> dict:
        return {
            "risk_level": self.risk_level,
            "rationale": self.rationale,
            "matched_signals": list(self.matched_signals),
            "requires_confirmation": self.requires_confirmation,
        }


def _jsonish(value: Any) -> str:
    try:
        import json
        return json.dumps(value, sort_keys=True)
    except Exception:
        return str(value)


def evaluate_trust_filter(
    objective: str,
    capability_name: str,
    params: dict | None,
    policy: dict | None = None,
) -> TrustFilterVerdict:
    """
    ConnectOnion-style pre-execution trust filter, implemented as a deterministic
    policy gate for high-risk capabilities and suspicious parameters.
    """
    params = params or {}
    policy = policy or {}
    matched: list[str] = []
    lowered_cap = capability_name.lower()
    flattened = " ".join(
        str(part).lower()
        for part in [objective, capability_name, _jsonish(params)]
        if part
    )

    if any(name in lowered_cap for name in HIGH_RISK_CAPABILITY_NAMES):
        matched.append(f"capability:{capability_name}")

    for keyword in HIGH_RISK_KEYWORDS:
        if keyword in flattened:
            matched.append(f"keyword:{keyword}")

    if lowered_cap == "file_ops" and str(params.get("operation", "")).lower() in {
        "delete", "move", "organize", "write"
    }:
        matched.append(f"file_op:{params.get('operation')}")

    if lowered_cap == "web_browse" and str(params.get("action", "")).lower() in {
        "interact", "fill_form"
    }:
        matched.append(f"browser_action:{params.get('action')}")

    if lowered_cap == "python_sandbox":
        code = str(params.get("code", "")).lower()
        if any(token in code for token in ("subprocess", "socket", "requests", "os.remove", "shutil.rmtree")):
            matched.append("sandbox:dangerous_code_pattern")

    review_policy = policy.get("review_required_capabilities", []) if isinstance(policy, dict) else []
    if capability_name in review_policy:
        matched.append("policy:review_required")

    if not matched:
        return TrustFilterVerdict(
            requires_confirmation=False,
            risk_level="low",
            rationale="No high-risk side effects detected for this step.",
            matched_signals=[],
        )

    high_risk = any(
        signal.startswith(("keyword:", "browser_action:", "sandbox:", "file_op:", "policy:"))
        for signal in matched
    )
    return TrustFilterVerdict(
        requires_confirmation=True,
        risk_level="high" if high_risk else "medium",
        rationale="This step could affect external systems, local files, or irreversible state.",
        matched_signals=matched,
    )


# ── Strategy decision point factory ──────────────────────────────────────────

def make_strategy_decision_point(
    dp_id: str,
    candidates: list[Any],  # list[CostEstimate]
    cost_model: Any,        # CostModel
) -> DecisionPoint:
    """
    Build a "strategy" DecisionPoint when the cost engine finds near-equal strategies.
    Used in MasterAgent._act() when StrategySelector.should_present_as_decision() is True.
    """
    options = []
    for i, estimate in enumerate(candidates):
        cost_str = (
            f"~${estimate.dollar_cost_cents / 100:.4f}"
            if estimate.dollar_cost_cents > 0
            else "free"
        )
        opt = DecisionOption(
            id=estimate.strategy_label,
            label=estimate.strategy_label.replace("_", " ").title(),
            description=estimate.rationale,
            pros=[
                f"Cost: {cost_str}",
                f"Time: ~{estimate.time_seconds:.0f}s",
                f"Confidence: {estimate.confidence:.0%}",
            ],
            cons=[],
            is_default=(i == 0),
        )
        options.append(opt)

    return DecisionPoint(
        id=dp_id,
        question="How should I execute this task?",
        options=options,
        category="strategy",
        context="These strategies have similar cost/time tradeoffs. Pick your preference.",
        required=False,  # agent will use the first if user ignores
    )
