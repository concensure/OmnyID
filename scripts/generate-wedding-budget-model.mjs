import { readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const sourcePath = resolve(root, "solid-ui/src/lib/wedding-budget-model.v1.json");
const outputPath = resolve(root, "wedding/assets/js/budget-model.v1.js");
const source = JSON.parse(await readFile(sourcePath, "utf8"));
const targets = source.categories.reduce((sum, category) => sum + category.targetShare, 0);

if (targets !== 100) {
  throw new Error(`Wedding budget target shares must total 100; received ${targets}.`);
}

const output = [
  "// Generated by scripts/generate-wedding-budget-model.mjs. Do not edit by hand.",
  `window.OMNYID_WEDDING_BUDGET_MODEL_V1 = ${JSON.stringify(source, null, 2)};`,
  "",
].join("\n");

await writeFile(outputPath, output, "utf8");
console.log(`Generated ${outputPath}`);
