use serde_json::{Number, Value, json};

pub struct WorkflowTraceEventContext<'a> {
    pub trace_source: &'a str,
    pub trace_detail_mode: &'a str,
    pub trace_side_effects: &'a str,
    pub execution_mode: &'a str,
    pub provider_request_id: Option<&'a str>,
    pub provider_status_text: Option<&'a str>,
    pub provider_latency_ms: Option<i64>,
    pub deployment_id: Option<&'a str>,
    pub deployment_environment: Option<&'a str>,
    pub runtime_trigger_kind: Option<&'a str>,
    pub replay_of_run_id: Option<&'a str>,
    pub replay_original_deployment_id: Option<&'a str>,
    pub replay_effective_deployment_id: Option<&'a str>,
    pub replay_compared_to_deployment_id: Option<&'a str>,
    pub replay_matched_original_deployment: Option<bool>,
    pub replay_changed_node_count: Option<i64>,
    pub delivery_tier: Option<&'a str>,
    pub provider_route: Option<&'a str>,
}

impl<'a> WorkflowTraceEventContext<'a> {
    fn provenance_payload(&self) -> Value {
        json!({
            "provider_request_id": self.provider_request_id,
            "deployment_id": self.deployment_id,
            "deployment_environment": self.deployment_environment,
            "runtime_trigger_kind": self.runtime_trigger_kind,
            "replay_of_run_id": self.replay_of_run_id,
            "replay_original_deployment_id": self.replay_original_deployment_id,
            "replay_effective_deployment_id": self.replay_effective_deployment_id,
            "replay_compared_to_deployment_id": self.replay_compared_to_deployment_id,
            "replay_matched_original_deployment": self.replay_matched_original_deployment,
            "replay_changed_node_count": self.replay_changed_node_count,
            "delivery_tier": self.delivery_tier,
            "provider_route": self.provider_route,
        })
    }

    pub fn trace_origin_event(&self) -> Value {
        json!({
            "kind": "trace_origin",
            "title": "Trace origin",
            "summary": if self.trace_detail_mode == "simulated" {
                "Trace was generated by the workflow simulator with live side effects suppressed."
            } else if self.execution_mode == "replay" {
                "Trace was reconstructed from workflow orchestration state during replay mode."
            } else if self.trace_source == "live_connector" {
                "Trace includes provider-backed connector details and reflects an executed external action."
            } else {
                "Trace was derived from workflow orchestration state and can later be extended by live connector events."
            },
            "payload": {
                "trace_source": self.trace_source,
                "trace_detail_mode": self.trace_detail_mode,
                "trace_side_effects": self.trace_side_effects,
                "trace_execution_mode": self.execution_mode,
                "provider_request_id": self.provider_request_id,
                "deployment_id": self.deployment_id,
                "deployment_environment": self.deployment_environment,
                "runtime_trigger_kind": self.runtime_trigger_kind,
                "replay_of_run_id": self.replay_of_run_id,
                "replay_original_deployment_id": self.replay_original_deployment_id,
                "replay_effective_deployment_id": self.replay_effective_deployment_id,
                "replay_compared_to_deployment_id": self.replay_compared_to_deployment_id,
                "replay_matched_original_deployment": self.replay_matched_original_deployment,
                "replay_changed_node_count": self.replay_changed_node_count,
                "delivery_tier": self.delivery_tier,
                "provider_route": self.provider_route,
            },
        })
    }

    pub fn request_prepared_event(
        &self,
        request_summary: &str,
        action_service: &str,
        action_operation: Option<&str>,
    ) -> Value {
        json!({
            "kind": "request_prepared",
            "title": "Request prepared",
            "summary": request_summary,
            "payload": {
                "service": action_service,
                "operation": action_operation,
                "deployment_environment": self.deployment_environment,
                "provider_route": self.provider_route,
            },
        })
    }

    pub fn auth_checked_event(&self, auth_mode: &str) -> Value {
        json!({
            "kind": "auth_checked",
            "title": "Auth mode",
            "summary": format!("Execution mode is {}.", auth_mode.replace('_', " ")),
            "payload": {
                "auth_mode": auth_mode,
            },
        })
    }

    pub fn retry_policy_event(
        &self,
        max_attempts: i64,
        timeout_seconds: Option<i64>,
        on_timeout: &str,
    ) -> Value {
        json!({
            "kind": "retry_policy",
            "title": "Retry policy",
            "summary": match timeout_seconds {
                Some(timeout) => format!("Max {} attempt(s), timeout {}s, on-timeout {}.", max_attempts, timeout, on_timeout),
                None => format!("Max {} attempt(s), on-timeout {}.", max_attempts, on_timeout),
            },
            "payload": {
                "max_attempts": max_attempts,
                "timeout_seconds": timeout_seconds,
                "on_timeout": on_timeout,
            },
        })
    }

    pub fn connector_dispatch_event(&self) -> Value {
        json!({
            "kind": "connector_dispatch",
            "title": "Connector dispatch",
            "summary": match (self.provider_status_text, self.provider_request_id) {
                (Some(status_text), Some(request_id)) => format!("Provider acknowledged request {request_id} with status {status_text}."),
                (Some(status_text), None) => format!("Provider acknowledged the request with status {status_text}."),
                (None, Some(request_id)) => format!("Provider request {request_id} was issued to the external connector."),
                (None, None) => "External connector request was dispatched.".to_string(),
            },
            "payload": {
                "provider_request_id": self.provider_request_id,
                "provider_status_text": self.provider_status_text,
                "provider_latency_ms": self.provider_latency_ms,
                "deployment_id": self.deployment_id,
                "deployment_environment": self.deployment_environment,
                "runtime_trigger_kind": self.runtime_trigger_kind,
                "replay_original_deployment_id": self.replay_original_deployment_id,
                "replay_effective_deployment_id": self.replay_effective_deployment_id,
                "replay_compared_to_deployment_id": self.replay_compared_to_deployment_id,
                "replay_matched_original_deployment": self.replay_matched_original_deployment,
                "replay_changed_node_count": self.replay_changed_node_count,
                "delivery_tier": self.delivery_tier,
                "provider_route": self.provider_route,
            },
        })
    }

    pub fn normalize_live_connector_events(&self, live_connector_events: &[Value]) -> Vec<Value> {
        live_connector_events
            .iter()
            .filter_map(Value::as_object)
            .map(|event| {
                let kind = event
                    .get("kind")
                    .and_then(Value::as_str)
                    .unwrap_or("connector_event")
                    .to_string();
                let title = event
                    .get("title")
                    .and_then(Value::as_str)
                    .map(str::to_string)
                    .unwrap_or_else(|| kind.replace('_', " "));
                let summary = event
                    .get("summary")
                    .and_then(Value::as_str)
                    .map(str::to_string)
                    .unwrap_or_else(|| "Connector event received.".to_string());
                let mut payload = event
                    .get("payload")
                    .and_then(Value::as_object)
                    .cloned()
                    .unwrap_or_default();
                if payload.get("provider_request_id").is_none() {
                    if let Some(value) = event.get("provider_request_id") {
                        payload.insert("provider_request_id".to_string(), value.clone());
                    } else if let Some(value) = self.provider_request_id {
                        payload.insert(
                            "provider_request_id".to_string(),
                            Value::String(value.to_string()),
                        );
                    }
                }
                if payload.get("provider_status_text").is_none() {
                    if let Some(value) = event.get("provider_status_text") {
                        payload.insert("provider_status_text".to_string(), value.clone());
                    } else if let Some(value) = self.provider_status_text {
                        payload.insert(
                            "provider_status_text".to_string(),
                            Value::String(value.to_string()),
                        );
                    }
                }
                if payload.get("provider_latency_ms").is_none() {
                    if let Some(value) = event.get("provider_latency_ms") {
                        payload.insert("provider_latency_ms".to_string(), value.clone());
                    } else if let Some(value) = self.provider_latency_ms {
                        payload.insert(
                            "provider_latency_ms".to_string(),
                            Value::Number(Number::from(value)),
                        );
                    }
                }
                json!({
                    "kind": kind,
                    "title": title,
                    "summary": summary,
                    "payload": Value::Object(payload),
                })
            })
            .collect()
    }

    pub fn approval_prompt_event(
        &self,
        reason: &str,
        decision_point_id: Option<&str>,
        option_count: Option<usize>,
    ) -> Value {
        json!({
            "kind": "approval_prompt",
            "title": "Approval prompt",
            "summary": reason,
            "payload": {
                "decision_point_id": decision_point_id,
                "option_count": option_count,
            },
        })
    }

    pub fn policy_decision_event(&self, reason: &str, routing_mode: &str) -> Value {
        json!({
            "kind": "policy_decision",
            "title": "Policy decision",
            "summary": reason,
            "payload": {
                "routing_mode": routing_mode,
            },
        })
    }

    pub fn branch_routing_event(
        &self,
        routing_mode: &str,
        selected_labels: &[String],
        selected_node_id: Option<&str>,
    ) -> Option<Value> {
        if routing_mode == "fanout" && selected_labels.is_empty() && selected_node_id.is_none() {
            return None;
        }
        Some(json!({
            "kind": "branch_routing",
            "title": "Branch routing",
            "summary": if !selected_labels.is_empty() {
                format!("Routing used {} via label(s): {}.", routing_mode.replace('_', " "), selected_labels.join(", "))
            } else if let Some(target) = selected_node_id {
                format!("Routing used {} toward {}.", routing_mode.replace('_', " "), target)
            } else {
                format!("Routing used {}.", routing_mode.replace('_', " "))
            },
            "payload": {
                "routing_mode": routing_mode,
                "selected_labels": selected_labels,
                "selected_node_id": selected_node_id,
            },
        }))
    }

    pub fn retry_observed_event(&self, retry_count: i64) -> Option<Value> {
        if retry_count <= 0 {
            return None;
        }
        Some(json!({
            "kind": "retry_observed",
            "title": "Retry observed",
            "summary": format!("{} retry attempt(s) were consumed before completion.", retry_count),
            "payload": {
                "retry_count": retry_count,
            },
        }))
    }

    pub fn result_event(
        &self,
        result_summary: &str,
        connector_status: &str,
        status_code: Option<i64>,
    ) -> Value {
        let mut payload = self
            .provenance_payload()
            .as_object()
            .cloned()
            .unwrap_or_default();
        payload.insert(
            "connector_status".to_string(),
            Value::String(connector_status.to_string()),
        );
        payload.insert(
            "status_code".to_string(),
            status_code
                .map(|value| Value::Number(Number::from(value)))
                .unwrap_or(Value::Null),
        );
        payload.insert(
            "provider_status_text".to_string(),
            self.provider_status_text
                .map(|value| Value::String(value.to_string()))
                .unwrap_or(Value::Null),
        );
        payload.insert(
            "provider_latency_ms".to_string(),
            self.provider_latency_ms
                .map(|value| Value::Number(Number::from(value)))
                .unwrap_or(Value::Null),
        );
        json!({
            "kind": "result",
            "title": "Result",
            "summary": format!("{} ({connector_status}).", result_summary),
            "payload": Value::Object(payload),
        })
    }
}

#[cfg(test)]
mod tests {
    use super::WorkflowTraceEventContext;
    use serde_json::json;

    fn ctx<'a>() -> WorkflowTraceEventContext<'a> {
        WorkflowTraceEventContext {
            trace_source: "live_connector",
            trace_detail_mode: "provider",
            trace_side_effects: "executed",
            execution_mode: "live",
            provider_request_id: Some("req_123"),
            provider_status_text: Some("accepted"),
            provider_latency_ms: Some(482),
            deployment_id: Some("dep_1"),
            deployment_environment: Some("prod"),
            runtime_trigger_kind: Some("manual"),
            replay_of_run_id: None,
            replay_original_deployment_id: None,
            replay_effective_deployment_id: None,
            replay_compared_to_deployment_id: None,
            replay_matched_original_deployment: None,
            replay_changed_node_count: None,
            delivery_tier: Some("standard"),
            provider_route: Some("primary"),
        }
    }

    #[test]
    fn result_event_carries_connector_diagnostics() {
        let event = ctx().result_event("Slack notifier completed.", "ok", Some(200));
        assert_eq!(event["kind"].as_str(), Some("result"));
        assert_eq!(
            event["payload"]["provider_request_id"].as_str(),
            Some("req_123")
        );
        assert_eq!(event["payload"]["status_code"].as_i64(), Some(200));
    }

    #[test]
    fn normalize_live_connector_events_backfills_provider_fields() {
        let events = ctx().normalize_live_connector_events(&[json!({
            "kind": "provider_callback",
            "summary": "Provider callback received."
        })]);
        assert_eq!(
            events[0]["payload"]["provider_request_id"].as_str(),
            Some("req_123")
        );
        assert_eq!(
            events[0]["payload"]["provider_latency_ms"].as_i64(),
            Some(482)
        );
    }
}
