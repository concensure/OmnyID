// @locs-version: 1.0
export type MedicalConceptGraphCapabilityLevel =
  | "available_now"
  | "partial_foundation"
  | "requires_ontology_investment";

export type MedicalConceptGraphCapability = {
  level: MedicalConceptGraphCapabilityLevel;
  headline: string;
  currentStrengths: string[];
  missingCapabilities: string[];
  implementationSequence: string[];
  defensibilitySummary: string;
};

export function buildMedicalConceptGraphCapabilityState(input?: {
  hasRetainedSources?: boolean | null;
  hasKnowledgeGraph?: boolean | null;
  hasStructuredDrillExports?: boolean | null;
  hasMedicalOntology?: boolean | null;
  hasDynamicQuestionRenderer?: boolean | null;
}): MedicalConceptGraphCapability {
  const hasFoundation = Boolean(input?.hasRetainedSources || input?.hasKnowledgeGraph || input?.hasStructuredDrillExports);
  const hasFullSystem = Boolean(input?.hasMedicalOntology && input?.hasDynamicQuestionRenderer);

  if (hasFullSystem) {
    return {
      level: "available_now",
      headline: "Concept-graph question regeneration is available when the ontology and dynamic renderer are both present.",
      currentStrengths: [
        "Structured medical concepts can drive freshly phrased recall prompts.",
        "Question attempts can measure concept mastery rather than static card memorization.",
      ],
      missingCapabilities: [],
      implementationSequence: [
        "Keep ontology review and SME governance active.",
        "Use attempt evidence to select graph edges needing retrieval practice.",
        "Audit generated questions for source coverage and clinical safety.",
      ],
      defensibilitySummary: "The moat is the reviewed medical ontology plus attempt-calibrated question generation, not the UI.",
    };
  }

  return {
    level: hasFoundation ? "partial_foundation" : "requires_ontology_investment",
    headline: hasFoundation
      ? "OmnyID has the foundation for graph-backed drills, but not a full medical curriculum ontology yet."
      : "This requires a dedicated medical ontology and dynamic question-generation layer before it is credible.",
    currentStrengths: [
      "Retained study sources can carry course, unit, chapter, and source metadata.",
      "Knowledge Graph and supertag flows can narrow a study focus and recommend drill generation.",
      "Quiz, flashcard, and practice-question outputs can be exported with answer policy and structured row metadata.",
    ],
    missingCapabilities: [
      "A reviewed ontology linking pathophysiology, pharmacology, presentation, investigations, management, contraindications, and systems.",
      "A dynamic question renderer that samples graph paths and rephrases prompts without changing the tested concept.",
      "Attempt history mapped to ontology nodes and edges, so the session tests weak concepts instead of replaying saved cards.",
      "Medical safety review, source provenance, and curriculum-version governance for high-stakes clinical content.",
    ],
    implementationSequence: [
      "Define the ontology schema for condition, mechanism, drug, symptom, investigation, management, and contraindication nodes.",
      "Import or curate a small reviewed pilot domain before attempting all medicine, for example cardiovascular pharmacology.",
      "Map uploaded/LMS/user-provided material into ontology-linked source claims with chapter, unit, and curriculum tags.",
      "Generate fresh questions from graph traversal patterns, then store attempts against ontology nodes and edges.",
      "Expose Anki-style export as an optional snapshot, while keeping OmnyID review sessions graph-regenerated by default.",
    ],
    defensibilitySummary: "The project can support this direction architecturally, but the hard, defensible part is the SME-reviewed medical graph and attempt-calibrated renderer. That is months of curriculum modeling, not a simple flashcard feature.",
  };
}
