"""Build postgres/data/2026-11-05_unconventional_venues_import.sql from unconventional_venues_2026-11-05.json.

New venues are inserted (ON CONFLICT DO NOTHING). Venues already staged or in the DB only get blank-filled
attributes and unioned style tags. Special category lives in evidence->'special_category' (jsonb array of
slugs such as 'boat', 'museum') so it can be filtered later:
    SELECT vendor_id FROM wedding_vendors WHERE evidence->'special_category' ? 'boat';
Run after the 2026-10-19 wedlockers_urbanlist_import.sql and the WeddingNSW load so matched rows exist.
"""
import json
import re
from pathlib import Path

HERE = Path(__file__).parent
OUT = HERE.parents[3] / "postgres" / "data" / "2026-11-05_unconventional_venues_import.sql"
LABEL = "Unconventional venues import 2026-11-05"
TS = "TIMESTAMPTZ '2026-11-05 00:00:00+00'"
ATTR_COLS = ("vendor_id, attribute_key, value, status, confidence, authority, source_url, source_label, "
             "retrieved_at, notes")


def q(s):
    return "NULL" if s is None else "'" + str(s).replace("'", "''") + "'"


def j(v):
    return q(json.dumps(v, ensure_ascii=False)) + "::jsonb"


def slug(name):
    s = re.sub(r"\(|\)", "", name.lower().replace("&", "and").replace("'", "").replace("’", ""))
    return re.sub(r"[^a-z0-9]+", "-", s).strip("-")


def attr(vid, key, value, src, notes=None, conf=0.8, checked_at="2026-11-05"):
    retrieved_at = f"TIMESTAMPTZ '{checked_at} 00:00:00+00'"
    return (f"({q(vid)}, {q(key)}, {j(value)}, 'known', {conf}, 'primary_official', {q(src)}, "
            f"{q(LABEL)}, {retrieved_at}, {q(notes)})")


def canonical_vendor_ref(vid, vendor_slug):
    """Resolve staged/generated IDs to the canonical row that owns the slug."""
    return ("(SELECT vendor_id FROM wedding_vendors "
            f"WHERE vendor_id = {q(vid)} OR vendor_slug = {q(vendor_slug)} "
            f"ORDER BY CASE WHEN vendor_id = {q(vid)} THEN 0 ELSE 1 END LIMIT 1)")


def union_tags(vendor_ref, tags, src):
    return (f"INSERT INTO wedding_vendor_attributes ({ATTR_COLS})\nSELECT {vendor_ref}, 'style_tags', {j(tags)}, "
            f"'known', 0.8, 'primary_official', {q(src)}, {q(LABEL)}, {TS}, NULL\n"
            f"WHERE {vendor_ref} IS NOT NULL\n"
            "ON CONFLICT (vendor_id, attribute_key) DO UPDATE SET value = (\n"
            "    SELECT to_jsonb(ARRAY(SELECT DISTINCT x FROM jsonb_array_elements_text(\n"
            "        wedding_vendor_attributes.value || EXCLUDED.value) AS x)))\n"
            "WHERE jsonb_typeof(wedding_vendor_attributes.value) = 'array';")


data = json.loads((HERE / "unconventional_venues_2026-11-05.json").read_text(encoding="utf-8"))
vendors, attrs = [], []
for v in data["new_venues"]:
    s = slug(v["vendor_name"])
    vid = "venue-" + s
    src = v["sources"][0]
    checked_at = v.get("source_checked_at") or "2026-11-05"
    notes = " ".join(x for x in (v.get("capacity_note"), v.get("price_note") and
                                 f"Price (operator site, verify before booking): {v['price_note']}") if x) or None
    evidence = {"source": "unconventional_venues_import", "imported": "2026-11-05",
                "special_category": v["special_category"], "special_subtype": v["special_subtype"],
                "sources": v["sources"], "flags": v["flags"]}
    labels = ["unconventional-import", "verify-before-booking"] + [
        f for f in v["flags"] if f in ("needs_contact_lookup", "verify_trading", "verify_availability")]
    arr = "ARRAY[" + ", ".join(q(x) for x in labels) + "]"
    vendors.append(
        f"({q(vid)}, {q(s)}, {q(v['vendor_name'])}, {q(v['category'])}, {q(v['service_area'])}, "
        f"{q(v['address'])}, {q(v['website_url'])}, {q(v['contact_phone'])}, {q(v['contact_email'])}, "
        f"{q(src)}, {q(LABEL)}, {q(checked_at)}, 'active', {q(notes)}, {j(evidence)}, {arr})")
    attrs.append(attr(vid, "style_tags", v["style_tags"], src, checked_at=checked_at))
    attrs.append(attr(vid, "editorial_summary", v["editorial_summary"], src, checked_at=checked_at))
    for key in ("capacity_seated_max", "capacity_standing_max"):
        if v.get(key):
            attrs.append(attr(vid, key, v[key], src, v.get("capacity_note"), checked_at=checked_at))

lines = [
    "-- Operator data load (not a migration): unconventional Sydney venues (cumulative batches), scraped 2026-11-05.",
    "-- Generated by Documents/design/wedding planner/unconventional-venues-import-2026-11-05/build_sql.py. Idempotent.",
    "-- Special category is stored in evidence->'special_category' and evidence->'special_subtype' (jsonb arrays).",
    "BEGIN;", "",
    "INSERT INTO wedding_vendors (vendor_id, vendor_slug, vendor_name, category, service_area, address,",
    "    website_url, contact_phone, contact_email, source_url, source_label, source_checked_at, status,",
    "    notes, evidence, caveat_labels)", "VALUES",
    ",\n".join(vendors), "ON CONFLICT DO NOTHING;", "",
    "INSERT INTO wedding_vendor_attributes (" + ATTR_COLS + ")", "VALUES",
    ",\n".join(attrs), "ON CONFLICT (vendor_id, attribute_key) DO NOTHING;", "",
]

for m in data["matched_existing"]:
    vid = m["db_vendor_id"] or "venue-" + slug(m["matches"])
    vendor_ref = canonical_vendor_ref(vid, slug(m["matches"]))
    src = m["sources"][0]
    merged = ", ".join(
        f"{q(k)}, (SELECT to_jsonb(ARRAY(SELECT DISTINCT x FROM jsonb_array_elements_text("
        f"COALESCE(evidence->{q(k)}, '[]'::jsonb) || {j(m[k])}) AS x ORDER BY x)))"
        for k in ("special_category", "special_subtype"))
    lines.append(f"UPDATE wedding_vendors SET evidence = evidence || jsonb_build_object({merged}) "
                 f"WHERE vendor_id = {vendor_ref};")
    for key, val in (m["fill_if_blank"] or {}).items():
        if key in ("address", "website_url", "contact_phone", "contact_email"):
            lines.append(f"UPDATE wedding_vendors SET {key} = {q(val)} "
                         f"WHERE vendor_id = {vendor_ref} AND COALESCE({key}, '') = '';")
        if key in ("capacity_seated_max", "capacity_standing_max"):
            lines.append(
                f"INSERT INTO wedding_vendor_attributes ({ATTR_COLS})\nSELECT {vendor_ref}, {q(key)}, {j(val)}, 'known', "
                f"0.8, 'primary_official', {q(src)}, {q(LABEL)}, {TS}, {q(m['capacity_note'])}\n"
                f"WHERE {vendor_ref} IS NOT NULL\n"
                "ON CONFLICT (vendor_id, attribute_key) DO NOTHING;")
    lines.append(union_tags(vendor_ref, m["extra_style_tags"], src))
lines += ["", "COMMIT;", ""]
OUT.write_text("\n".join(lines), encoding="utf-8")
print(f"{len(vendors)} new venues, {len(data['matched_existing'])} matched -> {OUT}")
