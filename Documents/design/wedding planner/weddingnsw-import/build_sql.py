"""Build the idempotent WeddingNSW operator import SQL from the reviewed JSON."""
from __future__ import annotations

import json
import re
from pathlib import Path


HERE = Path(__file__).parent
SOURCE = HERE / "weddingnsw_venues_2026-10-15.json"
OUTPUT = HERE.parents[3] / "postgres" / "data" / "2026-10-15_weddingnsw_import.sql"
CHECKED_AT = "2026-10-15"
SOURCE_LABEL = "WeddingNSW import 2026-10-15"


def sql(value: object | None) -> str:
    if value is None:
        return "NULL"
    return "'" + str(value).replace("'", "''") + "'"


def json_sql(value: object) -> str:
    return sql(json.dumps(value, ensure_ascii=False)) + "::jsonb"


def slug(value: str) -> str:
    return re.sub(r"^-+|-+$", "", re.sub(r"[^a-z0-9]+", "-", value.lower()))


def text_array(values: list[str]) -> str:
    return "ARRAY[" + ", ".join(sql(value) for value in values) + "]::text[]"


def attribute_insert(
    vendor_id: str,
    key: str,
    value: object,
    status: str,
    confidence: float,
    source_url: str | None,
    *,
    union_json_array: bool = False,
) -> str:
    conflict = (
        "DO UPDATE SET value = (SELECT jsonb_agg(DISTINCT item) FROM "
        "jsonb_array_elements(wedding_vendor_attributes.value || EXCLUDED.value) item), "
        "updated_by_user_id = NULL"
        if union_json_array
        else "DO NOTHING"
    )
    return (
        "INSERT INTO wedding_vendor_attributes (vendor_id, attribute_key, value, status, confidence, authority, "
        "source_url, source_label, retrieved_at)\n"
        f"SELECT {sql(vendor_id)}, {sql(key)}, {json_sql(value)}, {sql(status)}, {confidence}, 'directory', "
        f"{sql(source_url)}, {sql(SOURCE_LABEL)}, TIMESTAMPTZ '{CHECKED_AT} 00:00:00+00'\n"
        f"WHERE EXISTS (SELECT 1 FROM wedding_vendors WHERE vendor_id = {sql(vendor_id)})\n"
        f"ON CONFLICT (vendor_id, attribute_key) {conflict};"
    )


data = json.loads(SOURCE.read_text(encoding="utf-8"))
lines = [
    "-- Operator data load (not a migration): WeddingNSW venues reviewed 2026-10-15.",
    "-- Generated by Documents/design/wedding planner/weddingnsw-import/build_sql.py. Idempotent.",
    "-- Directory-derived prices and capacities remain estimated and carry verify-before-booking caveats.",
    "BEGIN;",
    "",
]

for vendor in data["new_venues"]:
    vendor_slug = slug(vendor["vendor_name"])
    vendor_id = f"venue-{vendor_slug}"
    flags = list(vendor.get("flags") or [])
    evidence = {
        "source": "weddingnsw_import",
        "imported": CHECKED_AT,
        "sources": [vendor.get("source_url")],
        "flags": flags,
    }
    caveats = ["weddingnsw-import", "verify-before-booking", *flags]
    lines.extend([
        "INSERT INTO wedding_vendors (vendor_id, vendor_slug, vendor_name, category, service_area, address,",
        "    website_url, contact_phone, contact_email, source_url, source_label, source_checked_at, status,",
        "    notes, evidence, caveat_labels)",
        "VALUES ("
        + ", ".join([
            sql(vendor_id), sql(vendor_slug), sql(vendor["vendor_name"]), sql(vendor.get("category") or "Venue"),
            sql(vendor.get("service_area") or "NSW"), sql(vendor.get("address")), sql(vendor.get("website_url")),
            sql(vendor.get("contact_phone")), sql(vendor.get("contact_email")), sql(vendor.get("source_url")),
            sql(SOURCE_LABEL), f"DATE '{CHECKED_AT}'", "'active'", "NULL", json_sql(evidence), text_array(caveats),
        ])
        + ") ON CONFLICT DO NOTHING;",
        attribute_insert(vendor_id, "style_tags", vendor.get("style_tags") or [], "known", 0.6, vendor.get("source_url"), union_json_array=True),
        attribute_insert(vendor_id, "editorial_summary", vendor.get("editorial_summary") or "", "known", 0.6, vendor.get("source_url")),
    ])
    for key in ("capacity_seated_max", "capacity_standing_max", "price_per_head_aud_from"):
        if vendor.get(key) is not None:
            lines.append(attribute_insert(vendor_id, key, vendor[key], "estimated", 0.6, vendor.get("source_url")))
    lines.append("")

for addition in data["existing_venue_additions"]:
    vendor_id = addition["db_vendor_id"]
    lines.extend([
        "UPDATE wedding_vendors",
        f"SET contact_email = COALESCE(contact_email, {sql(addition.get('email_to_fill_if_blank'))}), updated_at = NOW()",
        f"WHERE vendor_id = {sql(vendor_id)};",
        attribute_insert(vendor_id, "style_tags", addition.get("extra_style_tags") or [], "known", 0.6, None, union_json_array=True),
        attribute_insert(vendor_id, "editorial_summary", addition.get("extra_description") or "", "known", 0.6, None),
        "",
    ])

lines.extend(["COMMIT;", ""])
OUTPUT.parent.mkdir(parents=True, exist_ok=True)
OUTPUT.write_text("\n".join(lines), encoding="utf-8")
print(f"wrote {OUTPUT} ({len(data['new_venues'])} new, {len(data['existing_venue_additions'])} additions)")
